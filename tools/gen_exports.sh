#!/usr/bin/env bash
# SPDX-License-Identifier: GPL-3.0-or-later
# Generates the forwarding stubs of a proxy DLL from "<ordinal> <name>" lines.
#   tools/gen_exports.sh src/dll/d3d11_exports.txt src/dll d3d11 "D3D11CreateDevice D3D11CreateDeviceAndSwapChain"
#   tools/gen_exports.sh src/dll/d3d11_exports.txt src/dll d3d11 "D3D11CreateDevice D3D11CreateDeviceAndSwapChain" x86
#   tools/gen_exports.sh src/dll/dxgi_exports.txt src/dll dxgi "CreateDXGIFactory CreateDXGIFactory1 CreateDXGIFactory2"
#   tools/gen_exports.sh src/dll/dxgi_exports_x86.txt src/dll dxgi "" x86
#   tools/gen_exports.sh src/dll/vulkan_exports.txt src/dll vulkan "vkGetInstanceProcAddr vkGetDeviceProcAddr vkQueuePresentKHR"
#   tools/gen_exports.sh src/dll/vulkan_exports_x86.txt src/dll vulkan "" x86
# Outputs <out>/exports_<tag>.def, .asm and _gen.h. Exports listed in the
# 4th argument are implemented in C++ as Tessera_<name>.
set -euo pipefail
list=$1; out=$2; tag=$3; own=" ${4:-} "; arch=${5:-x64}

def=$out/exports_$tag.def; asm=$out/exports_$tag.asm; hdr=$out/exports_${tag}_gen.h
n=$(grep -c . "$list")

if [[ $arch == x86 ]]; then
  def=$out/exports_${tag}_x86.def; asm=$out/exports_${tag}_x86.asm
  # The x86 build uses the x64 _gen.h indices: both lists must name the same exports in the same order.
  if [[ ! -f $hdr ]] || ! diff -q <(awk '{print $2}' "$list") <(sed -n 's/^    "\(.*\)",$/\1/p' "$hdr") > /dev/null; then
    echo "error: $list must name the exports of $hdr in the same order" >&2; exit 1
  fi
  {
    echo "; Generated by tools/gen_exports.sh - do not edit."
    echo "EXPORTS"
    while read -r ord name; do
      case $name in
        D3D11CreateDevice) symbol=_Tessera_D3D11CreateDevice@40 ;;
        D3D11CreateDeviceAndSwapChain) symbol=_Tessera_D3D11CreateDeviceAndSwapChain@48 ;;
        CreateDXGIFactory|CreateDXGIFactory1) symbol=_Tessera_${name}@8 ;;
        CreateDXGIFactory2) symbol=_Tessera_CreateDXGIFactory2@12 ;;
        vkGetInstanceProcAddr|vkGetDeviceProcAddr|vkQueuePresentKHR) symbol=_Tessera_${name}@8 ;;
        *) symbol=stub_$name ;;
      esac
      echo "    $name=$symbol @$ord"
    done < "$list"
  } > "$def"
  {
    cat <<EOF
; Generated by tools/gen_exports.sh - do not edit.
.686p
.model flat
; No language type: names carry their x86 C decoration, so ml and llvm-ml (which
; does not decorate) emit the same symbols.
EXTERN _tessera_resolve:PROC
PUBLIC _tessera_real
.data
ALIGN 4
_tessera_real DWORD $n DUP(0)
.code

; WINAPI arguments are on the original caller's stack. Only the target
; is allowed to pop them. Preserve ECX/EDX for register arguments as well.
forward MACRO name, index
_stub_&name PROC
    mov eax, DWORD PTR [_tessera_real + index * 4]
    test eax, eax
    jnz @F
    push ecx
    push edx
    push index
    call _tessera_resolve
    add esp, 4
    pop edx
    pop ecx
@@:
    jmp eax
_stub_&name ENDP
ENDM

EOF
    i=0
    while read -r ord name; do
      echo "forward $name, $i"
      i=$((i + 1))
    done < "$list"
    echo "END"
  } > "$asm"
  echo "generated $n x86 exports -> $def $asm"
  exit
fi

{
  echo "; Generated by tools/gen_exports.sh — do not edit."
  echo "EXPORTS"
  while read -r ord name; do
    if [[ $own == *" $name "* ]]; then echo "    $name=Tessera_$name @$ord"
    else echo "    $name=stub_$name @$ord"; fi
  done < "$list"
} > "$def"

{
  echo "; Generated by tools/gen_exports.sh — do not edit."
  echo "; Each stub jumps to the real export; the first call resolves it."
  echo "EXTERN tessera_resolve:PROC"
  echo "PUBLIC tessera_real"
  echo ".data"
  echo "ALIGN 8"
  echo "tessera_real QWORD $n DUP(0)"
  echo ".code"
  cat <<'EOF'
; Saves the argument registers, resolves export r11d, restores and jumps.
tessera_resolve_thunk PROC FRAME
    push rcx
    .pushreg rcx
    push rdx
    .pushreg rdx
    push r8
    .pushreg r8
    push r9
    .pushreg r9
    sub rsp, 104
    .allocstack 104
    .endprolog
    movdqu xmmword ptr [rsp+32], xmm0
    movdqu xmmword ptr [rsp+48], xmm1
    movdqu xmmword ptr [rsp+64], xmm2
    movdqu xmmword ptr [rsp+80], xmm3
    mov ecx, r11d
    call _tessera_resolve
    movdqu xmm0, xmmword ptr [rsp+32]
    movdqu xmm1, xmmword ptr [rsp+48]
    movdqu xmm2, xmmword ptr [rsp+64]
    movdqu xmm3, xmmword ptr [rsp+80]
    add rsp, 104
    pop r9
    pop r8
    pop rdx
    pop rcx
    db 48h              ; REX.W jmp: an epilogue the x64 unwinder recognises
    jmp rax
tessera_resolve_thunk ENDP
EOF
  i=0
  while read -r ord name; do
    echo ""
    echo "stub_$name PROC"
    echo "    mov rax, qword ptr [tessera_real + $((i * 8))]"
    echo "    test rax, rax"
    echo "    jz @F"
    echo "    jmp rax"
    echo "@@:"
    echo "    mov r11d, $i"
    echo "    jmp tessera_resolve_thunk"
    echo "stub_$name ENDP"
    i=$((i + 1))
  done < "$list"
  echo "END"
} > "$asm"

{
  echo "// Generated by tools/gen_exports.sh — do not edit."
  echo "#pragma once"
  echo "namespace tessera::exports {"
  echo "inline constexpr int kCount = $n;"
  echo "inline constexpr const char* kNames[kCount] = {"
  while read -r ord name; do echo "    \"$name\","; done < "$list"
  echo "};"
  i=0
  while read -r ord name; do echo "inline constexpr int k$name = $i;"; i=$((i + 1)); done < "$list"
  echo "}  // namespace tessera::exports"
} > "$hdr"
echo "generated $n exports -> $def $asm $hdr"
