# Generates the forwarding stubs of a proxy DLL from "<ordinal> <name>" lines.
#   tools/gen_exports.sh src/dll/d3d11_exports.txt src/dll d3d11 "D3D11CreateDevice D3D11CreateDeviceAndSwapChain"
# Outputs <out>/exports_<tag>.def, .asm and _gen.h. Exports listed in the
# 4th argument are implemented in C++ as Tessera_<name>.
set -euo pipefail
list=$1; out=$2; tag=$3; own=" ${4:-} "

def=$out/exports_$tag.def; asm=$out/exports_$tag.asm; hdr=$out/exports_${tag}_gen.h
n=$(grep -c . "$list")

{
  echo "; Generated by tools/gen_exports.sh — do not edit."
  echo "EXPORTS"
  while read -r ord name; do
    if [[ $own == *" $name "* ]]; then echo "    $name=Tessera_$name @$ord"
    else echo "    $name=stub_$name @$ord"; fi
  done < "$list"
} > "$def"

{
  echo "; Generated by tools/gen_exports.sh — do not edit."
  echo "; Each stub jumps to the real export; the first call resolves it."
  echo "EXTERN tessera_resolve:PROC"
  echo "PUBLIC tessera_real"
  echo ".data"
  echo "ALIGN 8"
  echo "tessera_real QWORD $n DUP(0)"
  echo ".code"
  cat <<'EOF'
; Saves the argument registers, resolves export r11d, restores and jumps.
tessera_resolve_thunk PROC FRAME
    push rcx
    .pushreg rcx
    push rdx
    .pushreg rdx
    push r8
    .pushreg r8
    push r9
    .pushreg r9
    sub rsp, 104
    .allocstack 104
    .endprolog
    movdqu xmmword ptr [rsp+32], xmm0
    movdqu xmmword ptr [rsp+48], xmm1
    movdqu xmmword ptr [rsp+64], xmm2
    movdqu xmmword ptr [rsp+80], xmm3
    mov ecx, r11d
    call tessera_resolve
    movdqu xmm0, xmmword ptr [rsp+32]
    movdqu xmm1, xmmword ptr [rsp+48]
    movdqu xmm2, xmmword ptr [rsp+64]
    movdqu xmm3, xmmword ptr [rsp+80]
    add rsp, 104
    pop r9
    pop r8
    pop rdx
    pop rcx
    db 48h              ; REX.W jmp: an epilogue the x64 unwinder recognises
    jmp rax
tessera_resolve_thunk ENDP
EOF
  i=0
  while read -r ord name; do
    echo ""
    echo "stub_$name PROC"
    echo "    mov rax, qword ptr [tessera_real + $((i * 8))]"
    echo "    test rax, rax"
    echo "    jz @F"
    echo "    jmp rax"
    echo "@@:"
    echo "    mov r11d, $i"
    echo "    jmp tessera_resolve_thunk"
    echo "stub_$name ENDP"
    i=$((i + 1))
  done < "$list"
  echo "END"
} > "$asm"

{
  echo "// Generated by tools/gen_exports.sh — do not edit."
  echo "#pragma once"
  echo "namespace tessera::exports {"
  echo "inline constexpr int kCount = $n;"
  echo "inline constexpr const char* kNames[kCount] = {"
  while read -r ord name; do echo "    \"$name\","; done < "$list"
  echo "};"
  i=0
  while read -r ord name; do echo "inline constexpr int k$name = $i;"; i=$((i + 1)); done < "$list"
  echo "}  // namespace tessera::exports"
} > "$hdr"
echo "generated $n exports -> $def $asm $hdr"
